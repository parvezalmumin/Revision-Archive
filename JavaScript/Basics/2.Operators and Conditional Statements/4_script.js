// ASSIGNMENT OPERATORS


// 1. Basic Assignment (=)

let a = 10;

console.log("Basic Assignment:");
console.log("a =", a);


// 2. Addition Assignment (+=)

let b = 10;

b += 5;

console.log("Addition Assignment:");
console.log("b =", b);


// 3. Subtraction Assignment (-=)

let c = 10;

c -= 3;

console.log("Subtraction Assignment:");
console.log("c =", c);


// 4. Multiplication Assignment (*=)

let d = 10;

d *= 2;

console.log("Multiplication Assignment:");
console.log("d =", d);


// 5. Division Assignment (/=)

let e = 20;

e /= 4;

console.log("Division Assignment:");
console.log("e =", e);


// 6. Remainder Assignment (%=)

let f = 17;

f %= 5;

console.log("Remainder Assignment:");
console.log("f =", f);


// 7. Exponentiation Assignment (**=)

let g = 3;

g **= 2;

console.log("Exponentiation Assignment:");
console.log("g =", g);


// REAL EXAMPLE

let money = 1000;

console.log("Starting money:", money);

// Earn 500
money += 500;

console.log("After earning:", money);

// Spend 200
money -= 200;

console.log("After spending:", money);

// Double the money
money *= 2;

console.log("After doubling:", money);

// Divide the money
money /= 2;

console.log("After dividing:", money);