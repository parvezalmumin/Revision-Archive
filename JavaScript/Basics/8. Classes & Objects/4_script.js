     class Student {
        constructor(name, age) {
          this.name = name;
          this.age = age;
        }
      }

      const student1 = new Student("Mumin", 23);
      const student2 = new Student("Rahim", 22);

      console.log(student1.name); // Mumin
      console.log(student1.age); // 23

      console.log(student2.name); // Rahim
      console.log(student2.age); // 22

